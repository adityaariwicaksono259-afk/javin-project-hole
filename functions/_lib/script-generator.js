// Commit helper — push file ke GitHub (bisa multi-file)
// ============================================
import { getFile, putFile } from './github.js';

export async function commitGeneratedFiles(env, owner, repo, files, commitMessage) {
  const cfg = {
    token: env.GITHUB_TOKEN || '',
    owner: owner,
    repo: repo,
    branch: 'main'
  };

  if (!cfg.token) return { ok: false, message: 'GITHUB_TOKEN kosong' };

  const results = [];

  for (const file of files) {
    // Cek apakah file udah ada (buat dapetin sha kalau update)
    let existingSha = null;
    try {
      const existing = await getFile(env, file.path);
      if (existing.ok) existingSha = existing.sha;
    } catch (e) {}

    const url = `https://api.github.com/repos/${cfg.owner}/${cfg.repo}/contents/${file.path}`;
    const b64 = btoa(unescape(encodeURIComponent(file.content)));

    const body = {
      message: commitMessage,
      content: b64,
      branch: cfg.branch
    };
    if (existingSha) body.sha = existingSha;

    const r = await fetch(url, {
      method: 'PUT',
      headers: {
        'Authorization': 'Bearer ' + cfg.token,
        'Accept': 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'JavinBot/1.0',
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(body)
    });

    if (!r.ok) {
      const err = await r.text();
      return { ok: false, message: `Commit ${file.path} gagal: HTTP ${r.status} — ${err.slice(0, 200)}` };
    }

    results.push(file.path);
  }

  return { ok: true, committed: results };
}

