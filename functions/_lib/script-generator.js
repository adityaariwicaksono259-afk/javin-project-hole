// Template Express server + cheerio + scraping helper
export function generateScraperScript(config) {
  const {
    name = 'my-scraper',
    upstream = '',
    path = '/scrape',
    params = [],
    method = 'GET',
    paramType = 'auto'
  } = config;

  // Format params
  const paramsList = params.length ? params : ['q'];
  const paramDestructure = paramsList.map(p => p + ' = req.query.' + p + ' || req.body.' + p).join(', ');

  return `// ============================================
// ${name} — Auto-generated by JAVIN Bot
// Generated: ${new Date().toISOString()}
// ============================================
// Cara deploy:
// 1. Buat repo GitHub baru: ${name}-backend
// 2. Copy file ini sebagai server.js
// 3. Buat package.json (lihat bawah)
// 4. Push ke GitHub
// 5. Deploy di render.com (New Web Service)
// 6. Copy URL-nya ke bot: /api <url>${path}
// ============================================

const express = require('express');
const axios = require('axios');
const cheerio = require('cheerio');

const app = express();
app.use(express.json());
app.use(express.urlencoded({ extended: true }));
app.use((req, res, next) => {
  res.header('Access-Control-Allow-Origin', '*');
  res.header('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  res.header('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') return res.sendStatus(200);
  next();
});

const UPSTREAM_BASE = '${upstream}';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

async function fetchPage(url) {
  const { data } = await axios.get(url, {
    headers: {
      'User-Agent': UA,
      'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
      'Accept-Language': 'id-ID,id;q=0.9,en;q=0.8',
      'Referer': UPSTREAM_BASE
    },
    timeout: 20000,
    maxRedirects: 5
  });
  return cheerio.load(data);
}

// ============================================
// ROUTES
// ============================================

app.get('/', (req, res) => {
  res.json({
    ok: true,
    service: '${name}',
    endpoint: '${path}',
    params: ${JSON.stringify(paramsList)},
    status: 'running'
  });
});

app.all('${path}', async (req, res) => {
  try {
    const { ${paramDestructure} } = Object.assign({}, req.query, req.body);

    // ====== BUILD UPSTREAM URL ======
    // ⚠️ EDIT BAGIAN INI sesuai kebutuhan scraping
    const targetUrl = UPSTREAM_BASE${paramsList.map((p, i) => {
      const sep = i === 0 ? '?' : '&';
      return ` + '${sep}${p}=' + encodeURIComponent(${p} || '')`;
    }).join('')};

    const $ = await fetchPage(targetUrl);

    // ====== PARSING ======
    // ⚠️ EDIT BAGIAN INI sesuai struktur HTML target
    // Contoh di bawah cuma template — sesuaikan dengan site target.

    const results = [];
    // Contoh selector generik (edit sesuai site):
    $('article, .item, .card, .result').each((i, el) => {
      if (i >= 30) return;
      const $el = $(el);
      const link = $el.find('a').first().attr('href') || '';
      const title = $el.find('h1, h2, h3, .title, .name').first().text().trim();
      const image = $el.find('img').first().attr('src') || $el.find('img').first().attr('data-src') || '';
      const desc = $el.find('p, .desc, .summary').first().text().trim().slice(0, 200);

      if (title || link) {
        results.push({ title, link, image, desc });
      }
    });

    res.json({
      ok: true,
      query: { ${paramDestructure} },
      count: results.length,
      results: results,
      source_url: targetUrl
    });

  } catch (e) {
    console.error('[ERROR]', e.message);
    res.status(500).json({ ok: false, error: e.message });
  }
});

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => console.log('Server running on port ' + PORT));
`;
}

