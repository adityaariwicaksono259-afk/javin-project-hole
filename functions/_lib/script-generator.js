// Bikin repo baru di GitHub
// ============================================
export async function createGithubRepo(env, repoName, isPrivate = true) {
  const token = env.GITHUB_TOKEN || '';
  if (!token) return { ok: false, message: 'GITHUB_TOKEN kosong' };

  const r = await fetch('https://api.github.com/user/repos', {
    method: 'POST',
    headers: {
      'Authorization': 'Bearer ' + token,
      'Accept': 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'User-Agent': 'JavinBot/1.0',
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      name: repoName,
      private: isPrivate,
      auto_init: false,
      description: 'Auto-generated by JAVIN Bot'
    })
  });

  if (!r.ok) {
    const err = await r.text();
    return { ok: false, message: `Buat repo gagal: HTTP ${r.status} — ${err.slice(0, 200)}` };
  }

  const j = await r.json();
  return {
    ok: true,
    repo: j.full_name,
    url: j.html_url,
    clone_url: j.clone_url
  };
}
